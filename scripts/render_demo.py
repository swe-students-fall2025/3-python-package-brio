"""Export actual Textcraft typewriter, scroll and wave function output to GIF."""
import argparse
from pathlib import Path
import sys
from PIL import Image, ImageDraw
from image_export import font, save_gif


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    sys.path.insert(0, str(args.root.resolve()/'src'))
    from minecraft_textcraft.render import render
    from minecraft_textcraft.animate import animate_typewriter, animate_scroll, animate_wave
    art = render('HELLO')
    effects = [('type', list(animate_typewriter(art, cps=36))),
               ('scroll', list(animate_scroll(art, cols_per_frame=2))),
               ('wave', list(animate_wave(art, amplitude=2, period_cols=10, frames=36)))]
    frames, durations = [], []
    max_cols = max(len(line) for _, fs in effects for text in fs for line in text.splitlines())
    max_rows = max(len(text.splitlines()) for _, fs in effects for text in fs)
    size = 22
    while size > 8:
        mono = font(size, mono=True)
        if mono.getlength('M') * max_cols <= 865 and (size + 2) * max_rows <= 320:
            break
        size -= 1
    mono = font(size, mono=True)
    row_height = size + 2
    assert mono.getlength('M') * max_cols <= 865 and row_height * max_rows <= 320
    for index, (effect, output_frames) in enumerate(effects):
        for i, text in enumerate(output_frames):
            frame = Image.new('RGB', (1000, 700), '#101925')
            d = ImageDraw.Draw(frame)
            d.text((35, 25), 'Minecraft Textcraft', font=font(30), fill='#e6f7ef')
            d.text((36, 71), 'Python package / CLI / real program output', font=font(17), fill='#94b3a6')
            for j, label in enumerate(['TYPEWRITER','SCROLL','WAVE']):
                x = 35+j*310
                d.rounded_rectangle((x, 111, x+285, 151), radius=7,
                                    fill='#22493a' if j == index else '#1b2b35')
                d.text((x+17, 124), label, font=font(15), fill='#80f1b3' if j == index else '#8fa5ab')
            d.rounded_rectangle((35, 179, 965, 620), radius=12, fill='#07110d', outline='#325045')
            for j, color in enumerate(['#fa7b79','#e8c565','#71cb8e']):
                x=56+j*24;d.ellipse((x,195,x+10,205),fill=color)
            d.text((55, 222), f'$ minecraft-textcraft HELLO --effect {effect} --color GREEN',
                   font=font(16, mono=True), fill='#b1cbbc')
            lines = text.splitlines()
            left = 500 - mono.getlength('M') * max_cols / 2
            for row, line in enumerate(lines):
                d.text((left, 276+row*row_height), line, font=mono, fill='#88f0af')
            d.text((36, 658), 'Frames generated by the package functions; exported with Pillow.',
                   font=font(17), fill='#9ab7a9')
            frames.append(frame)
            durations.append(1200 if i == len(output_frames)-1 else 85)
    output = args.output or args.root/'docs/media/textcraft-workflow.gif'
    save_gif(frames, durations, output)


if __name__ == '__main__':
    main()
